import Foundation

/// Drives an FTDI "Open DMX" style cable, where the Mac itself generates the DMX signal:
/// 250 kbaud 8N2, a BREAK (≥ 88 µs, we use ~150 µs), a mark-after-break, then start code 0 and
/// 512 slots — continuously, about 30 times per second.
///
/// Best effort by nature: macOS timing isn't real-time, so a busy Mac can stretch frames.
/// Used only for devices the user marked as Open DMX.
public final class OpenDMXDevice: DMXDevice, @unchecked Sendable {
    public struct Options: Sendable {
        public var frameInterval = 1.0 / 30
        public var breakDuration = 0.000_150
        public var markAfterBreak = 0.000_020
        public var baud = 250_000
        public var backoff: [Double] = [0.5, 1, 2, 3]

        public init() {}
    }

    public let id: String
    public let kind: DMXDeviceKind = .openDMX
    private let runtime: DeviceRuntime
    private let options: Options
    private let locate: @Sendable () -> String?

    public init(id: String, name: String = "Open DMX", options: Options = Options(),
                locate: @escaping @Sendable () -> String?) {
        self.id = id
        self.options = options
        self.locate = locate
        runtime = DeviceRuntime(snapshot: DMXDeviceSnapshot(id: id, kind: .openDMX, name: name, shortName: name))
    }

    public var snapshot: DMXDeviceSnapshot { runtime.snapshot }
    public func submit(port: Int, data: [UInt8]) { runtime.slot.submit(port: port, data: data) }
    public func start() { runtime.start(name: "Prism Open DMX \(id)") { [self] in self.run() } }
    public func stop(flushTimeout: Double) { runtime.stop(flushTimeout: flushTimeout) }
    public func reconnectNow() { runtime.requestReconnect() }
    public func markRemoved() { runtime.markRemoved() }
    public func setChangeHandler(_ handler: (@Sendable (DMXDeviceSnapshot) -> Void)?) { runtime.setChangeHandler(handler) }

    private func backoff(_ attempt: Int) -> Double {
        guard let last = options.backoff.last else { return 1 }
        return attempt < options.backoff.count ? options.backoff[max(0, attempt)] : last
    }

    private func run() {
        var attempt = 0
        while !runtime.isStopping {
            _ = runtime.consumeReconnect()
            _ = runtime.consumeRemoved()
            guard let path = locate() else {
                runtime.update { $0.state = .searching; $0.path = nil }
                runtime.pause(backoff(attempt))
                attempt += 1
                continue
            }
            runtime.beginConnecting(path: path)
            let port: SerialPort
            do {
                port = try SerialPort.open(path: path, baud: options.baud, twoStopBits: true)
            } catch let error as SerialPortError {
                switch error {
                case .busy: runtime.setState(.busy, error: error.message)
                case .notFound: runtime.setState(.searching)
                default: runtime.setState(.failed(error.message), error: error.message)
                }
                runtime.pause(error == .busy ? 2 : max(1, backoff(attempt)))
                attempt += 1
                continue
            } catch {
                runtime.setState(.failed("Prism couldn't open the Open DMX cable."))
                runtime.pause(2)
                continue
            }
            attempt = 0
            _ = port.setRTS(false)
            runtime.update {
                $0.state = .live
                $0.timing = "Generated by this Mac · about \(Int((1 / options.frameInterval).rounded())) fps"
                $0.lastError = nil
            }
            let lost = refreshLoop(port)
            port.close()
            if let lost {
                runtime.recordReconnect()
                runtime.update { $0.state = .searching; $0.lastError = lost }
                runtime.pause(backoff(0))
            }
        }
        runtime.setState(.stopped)
    }

    /// Sends frames continuously until stopped (nil) or the cable is lost (reason).
    private func refreshLoop(_ port: SerialPort) -> String? {
        var frame = [UInt8](repeating: 0, count: 513)
        while true {
            let started = PrismClock.now()
            if runtime.consumeRemoved() { return SerialPortError.disconnected.message }
            _ = runtime.consumeReconnect()
            let stopping = runtime.isStopping
            if let latest = runtime.slot.take(port: 1)?.data ?? runtime.slot.latestFrame(port: 1) {
                for i in 0..<512 { frame[i + 1] = i < latest.count ? latest[i] : 0 }
            }
            port.drainOutput()
            // BREAK + MARK-AFTER-BREAK. A cable that can't do BREAK still gets data; not fatal.
            if port.setBreak(true) {
                Sys.sleep(seconds: options.breakDuration)
                port.setBreak(false)
                Sys.sleep(seconds: options.markAfterBreak)
            }
            do {
                switch try port.write(frame, startTimeout: 0.03, finishTimeout: 0.15) {
                case .sent: runtime.recordSent(latency: nil, now: PrismClock.now())
                case .dropped: runtime.recordDropped()
                }
            } catch let error as SerialPortError {
                runtime.recordWriteError()
                return error.message
            } catch {
                return SerialPortError.disconnected.message
            }
            if stopping {
                port.drainOutput()
                return nil
            }
            let remaining = options.frameInterval - (PrismClock.now() - started)
            if remaining > 0 {
                let w = IOWait.wait(fd: -1, read: false, write: false, wakeFD: runtime.wakeFD, timeout: remaining)
                if w.woken { runtime.wake?.drain() }
            }
        }
    }
}

/// A device that only pretends: used by the screenshot tour, the self-test and previews.
/// It has no thread; its state is whatever the caller sets.
public final class SimulatedDMXDevice: DMXDevice, @unchecked Sendable {
    public let id: String
    public let kind: DMXDeviceKind
    private let state: Locked<DMXDeviceSnapshot>
    private let frames = Locked<[Int: [UInt8]]>([:])
    private let handler = Locked<(@Sendable (DMXDeviceSnapshot) -> Void)?>(nil)
    private let initialState: DMXDeviceState

    public init(id: String, kind: DMXDeviceKind = .enttecPro, name: String, shortName: String? = nil,
                serialNumber: String? = nil, firmware: String? = nil, timing: String? = nil,
                path: String? = nil, portCount: Int = 1, state: DMXDeviceState = .live) {
        self.id = id
        self.kind = kind
        initialState = state
        self.state = Locked(DMXDeviceSnapshot(id: id, kind: kind, name: name, shortName: shortName,
                                              state: .stopped, serialNumber: serialNumber, firmware: firmware,
                                              path: path, timing: timing, portCount: portCount))
    }

    public var snapshot: DMXDeviceSnapshot { state.value }

    /// Frames received per port.
    public func lastFrame(port: Int) -> [UInt8]? { frames.value[port] }

    public func submit(port: Int, data: [UInt8]) {
        frames.mutate { $0[port] = data }
        state.mutate { s in
            guard s.state == .live else { return }
            s.stats.framesSent &+= 1
            s.stats.lastSendTime = PrismClock.now()
            s.stats.updatesPerSecond = 40
            s.stats.lastLatencyMs = 0.4
            s.stats.averageLatencyMs = 0.4
        }
    }

    /// Changes the pretend state (e.g. `.searching` after being live = "unplugged").
    public func setState(_ newState: DMXDeviceState, warning: String? = nil) {
        let s: DMXDeviceSnapshot = state.mutate { s in
            s.state = newState
            if newState == .live { s.hasBeenLive = true }
            s.warning = warning
            return s
        }
        handler.value?(s)
    }

    public func start() { setState(initialState) }
    public func stop(flushTimeout: Double) { setState(.stopped) }
    public func reconnectNow() {}
    public func markRemoved() { setState(.searching) }
    public func setChangeHandler(_ handler: (@Sendable (DMXDeviceSnapshot) -> Void)?) { self.handler.value = handler }
}
